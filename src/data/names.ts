// PDF-тегі қателер көшірілмей түзетілді, әр түзету `fix` өрісінде жазылған.
import type { ClassId } from './types';

export interface NameItem {
  /** Формула (жартылай құрылымдық, F компонентімен көрсетіледі) */
  f: string;
  /** Жүйелік (IUPAC) атауы */
  sys: string;
  /** Тривиал немесе тарихи атауы */
  triv?: string;
  /** PDF-тен айырмашылығы, түзету себебі */
  fix?: string;
}

export interface NameGroup {
  id: string;
  title: string;
  /** Үлкен бөлім: жаттығуда сүзу үшін */
  part: 'hc' | 'o' | 'n';
  cls: ClassId;
  /** Жалпы формула */
  gen?: string;
  /** Атау қалай құрылады — қысқа ереже */
  rule: string;
  /** Жалпы формула тексерісі: H = a·C + b (тест үшін) */
  h?: [number, number];
  /** Атауда көміртек санына сай түбір болуы тиіс (тармақталмаған қатар) */
  rooted?: boolean;
  items: NameItem[];
}

