// ───────── Атау құрастырғыш: көміртек саны + класс → формула мен атау
export type BuildCls = 'alkane' | 'alkyl' | 'cyclo' | 'alkene' | 'alkyne' | 'diene' | 'alcohol' | 'aldehyde' | 'acid' | 'amine';

export const BUILD_CLS: { id: BuildCls; label: string; min: number }[] = [
  { id: 'alkane', label: 'Алкан', min: 1 }, { id: 'alkyl', label: 'Радикал', min: 1 }, { id: 'cyclo', label: 'Циклоалкан', min: 3 },
  { id: 'alkene', label: 'Алкен', min: 2 }, { id: 'alkyne', label: 'Алкин', min: 2 }, { id: 'diene', label: 'Алкадиен', min: 3 },
  { id: 'alcohol', label: 'Спирт', min: 1 }, { id: 'aldehyde', label: 'Альдегид', min: 1 }, { id: 'acid', label: 'Қышқыл', min: 1 },
  { id: 'amine', label: 'Амин', min: 1 },
];

const cnh = (c: number, h: number) => (c > 0 ? 'C' + (c > 1 ? c : '') : '') + 'H' + (h > 1 ? h : '');
const alkylName = (n: number) => (n === 10 ? 'децил' : ROOTS[n] + 'ил');

export function buildName(cls: BuildCls, n: number): { f: string; name: string; parts: string[]; gen: string } | null {
  const r = ROOTS[n];
  if (!r) return null;
  switch (cls) {
    case 'alkane': return { f: cnh(n, 2 * n + 2), name: r + 'ан', parts: [r, '-ан'], gen: 'CₙH₂ₙ₊₂' };
    case 'alkyl': return { f: cnh(n, 2 * n + 1), name: alkylName(n), parts: [n === 10 ? 'дец' : r, '-ил'], gen: 'CₙH₂ₙ₊₁' };
    case 'cyclo': return n < 3 ? null : { f: cnh(n, 2 * n), name: 'цикло' + r + 'ан', parts: ['цикло-', r, '-ан'], gen: 'CₙH₂ₙ' };
    case 'alkene': return n < 2 ? null : { f: cnh(n, 2 * n), name: r + 'ен' + (n >= 4 ? '-1' : ''), parts: [r, '-ен', ...(n >= 4 ? ['-1 (орны)'] : [])], gen: 'CₙH₂ₙ' };
    case 'alkyne': return n < 2 ? null : { f: cnh(n, 2 * n - 2), name: r + 'ин' + (n >= 4 ? '-1' : ''), parts: [r, '-ин', ...(n >= 4 ? ['-1 (орны)'] : [])], gen: 'CₙH₂ₙ₋₂' };
    case 'diene':
      if (n < 3) return null;
      return n === 3
        ? { f: 'C3H4', name: 'пропадиен', parts: ['проп', '-адиен'], gen: 'CₙH₂ₙ₋₂' }
        : { f: cnh(n, 2 * n - 2), name: r + 'адиен-1,3', parts: [r, '-адиен', '-1,3 (орындары)'], gen: 'CₙH₂ₙ₋₂' };
    case 'alcohol': return { f: cnh(n, 2 * n + 1) + 'OH', name: r + 'анол' + (n >= 3 ? '-1' : ''), parts: [r + 'ан', '-ол', ...(n >= 3 ? ['-1 (орны)'] : [])], gen: 'CₙH₂ₙ₊₁OH' };
    case 'aldehyde': return { f: n === 1 ? 'HCHO' : cnh(n - 1, 2 * n - 1) + 'CHO', name: r + 'аналь', parts: [r + 'ан', '-аль'], gen: 'Cₙ₋₁H₂ₙ₋₁CHO' };
    case 'acid': return { f: n === 1 ? 'HCOOH' : cnh(n - 1, 2 * n - 1) + 'COOH', name: r + 'ан қышқылы', parts: [r + 'ан', 'қышқылы'], gen: 'Cₙ₋₁H₂ₙ₋₁COOH' };
    case 'amine': return { f: cnh(n, 2 * n + 1) + 'NH2', name: alkylName(n) + 'амин', parts: [n === 10 ? 'децил' : r + 'ил', 'амин'], gen: 'CₙH₂ₙ₊₁NH₂' };
  }
}
