import type { Reaction } from '../data/types';

export function defaultBond(r: Reaction): string {
  switch (r.ty) {
    case 'comb': return 'Барлық C–C, C–H (және C–O, N–H) байланыстары үзіледі; CO₂ құрамында C=O, суда O–H байланыстары түзіледі.';
    case 'ferment': return 'Ферменттер көміртек тізбегін бөлшектейді: C–C байланыстары үзіліп, кіші молекулалар түзіледі.';
    case 'synth': return 'Бастапқы заттардағы байланыстар үзіліп, жаңа C–H, C–C немесе C–O байланыстары түзіледі.';
    case 'exch': return 'Иондар орын алмасады: жаңа иондық байланыстар түзіліп, тұнба, газ немесе су бөлінеді.';
    case 'decomp': return 'Молекуладағы C–C немесе C–H байланыстары үзіледі.';
    case 'ox': return 'C–H байланыстары үзіліп, C–O немесе C=O байланыстары түзіледі.';
    default: return 'Реагенттердегі байланыстар үзіліп, өнімдерде жаңа байланыстар түзіледі.';
  }
}

export function defaultMistake(r: Reaction): string {
  switch (r.ty) {
    case 'comb': return 'Оттекті ең соңында теңестір және заттың өз құрамындағы оттек атомдарын да санауды ұмытпа. Бөлшек коэффициент шықса, барлығын 2-ге көбейт.';
    case 'acidbase': case 'exch': return 'Тұздың формуласын жазғанда металдың валенттілігін ескер: мысалы, Ca²⁺ үшін екі қышқыл қалдығы керек.';
    case 'hydrol': return 'Гидролиз ортасын ескер: қышқылдық ортада қышқыл, сілтілік ортада тұз түзіледі.';
    case 'poly': return 'Полимер буынында мономердің қос байланысы жойылатынын (диендерде орнын ауыстыратынын) ескер.';
    case 'polycond': return 'Поликонденсацияда әр байланыс түзілгенде су бөлінетінін ұмытпа.';
    case 'ferment': return 'Ашу түрлерін шатастырма: спирттік — этанол мен CO₂, сүт қышқылды — сүт қышқылы, май қышқылды — бутан қышқылы, H₂ және CO₂.';
    case 'add': return 'Қосылу кезінде тек π-байланыс үзіледі, көміртек қаңқасы сақталады.';
    case 'subst': return 'Орынбасуда бір атом (топ) кетіп, екіншісі келеді: қосымша өнімді (HCl, HBr, H₂O) жазуды ұмытпа.';
    default: return 'Өнімнің құрылымдық формуласын жаз: молекулалық формула изомерлерді ажыратпайды.';
  }
}

